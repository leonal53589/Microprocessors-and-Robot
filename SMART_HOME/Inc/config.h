/* ==========================================================================
 * 2. 任务周期（全部为毫秒，主循环按时间戳非阻塞调度）
 * ========================================================================== */
#define CFG_DHT_PERIOD_MS       2000U   /* DHT11 采样间隔，模块要求 >= 1s     */
#define CFG_ADC_PERIOD_MS        200U   /* 电压表刷新周期                     */
#define CFG_KEY_PERIOD_MS         10U   /* 按键扫描周期（配合 20ms 消抖）     */
#define CFG_UI_PERIOD_MS         200U   /* 首页数值局部刷新周期               */
#define CFG_LED_BLINK_MS         250U   /* 越限红灯闪烁半周期 -> 约 2Hz       */
#define CFG_CAM_TIMEOUT_MS       400U   /* 摄像头一帧未完成 -> 判定失联       */
#define CFG_DHT_FAIL_LIMIT         3U   /* DHT11 连续失败次数 -> 判定故障     */
#define CFG_CAM_FAIL_LIMIT         3U   /* 摄像头连续失败次数 -> 判定故障     */

/* ==========================================================================
 * 3. 预警阈值（上限）与回差
 *    温度/湿度来自 DHT11（整数），电压来自 ADC（0.01V 分辨率）
 *    回差（hysteresis）的作用：值在阈值附近抖动时不会反复切换报警状态
 *        进入报警： value >  MAX
 *        退出报警： value <= MAX - HYST
 * ========================================================================== */
#define CFG_TEMP_MAX_C          30.0f   /* 温度上限 ℃            */
#define CFG_HUMI_MAX_PCT        70.0f   /* 湿度上限 %RH          */
#define CFG_VOLT_MAX_V           2.80f  /* 电压上限 V (RV1 可调) */

#define CFG_TEMP_HYST_C          1.0f   /* 温度回差 ℃            */
#define CFG_HUMI_HYST_PCT        2.0f   /* 湿度回差 %RH          */
#define CFG_VOLT_HYST_V          0.05f  /* 电压回差 V            */

/* ==========================================================================
 * 4. ADC 多次采样平均次数（抑制读数抖动）
 * ========================================================================== */
#define CFG_ADC_AVG_COUNT         16U

/* ==========================================================================
 * 5. 摄像头 RGB565 字节序
 *    DCMI 工作在 8 位模式，一个像素占 2 个字节，先到的是高字节。
 *    如果预览画面颜色明显不对（偏色，而不是花屏/撕裂），把它改成 1 再试。
 * ========================================================================== */
#define CFG_CAM_BYTE_SWAP          0

