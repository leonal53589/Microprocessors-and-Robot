#ifndef __CONFIG_H
#define __CONFIG_H

/* ==========================================================================
 * 1. 学生信息（显示在 LCD 状态栏）
 * ========================================================================== */
#define STUDENT_NAME    "蓝彦扬"
#define STUDENT_ID      "2024095004"
#define STUDENT_CLASS   "计软学院"

#define EXP_TITLE       "人脸录入与识别"
#define EXP_SUBTITLE    "微处理器与机器人  实验四"

/* ==========================================================================
 * 2. 人员与图库规模
 *    CFG_SLOTS_PER_PERSON 比最少要求多留 1 个，方便"拍模糊了重拍"
 * ========================================================================== */
#define CFG_PERSON_COUNT        5U      /* 录入人员数 1~5            */
#define CFG_SLOTS_PER_PERSON    6U      /* 每人槽位数（>= 5 张训练图）*/
#define CFG_MIN_SAMPLES         5U      /* 每人至少 5 张才算训练集够用 */
#define CFG_MAX_RECORDS         (CFG_PERSON_COUNT * CFG_SLOTS_PER_PERSON)

/* ==========================================================================
 * 3. 取景框：在 QVGA(320x240) 预览画面里的位置与大小
 *    本实验不做人脸检测，而是用固定取景框 + 由人自己对准，
 *    这样录入与识别用的是完全相同的裁剪方式（实验要求明确要求一致）
 * ========================================================================== */
#define CFG_CROP_W              160U
#define CFG_CROP_H              160U
#define CFG_CROP_X              ((320U - CFG_CROP_W) / 2U)   /* 水平居中 = 80 */
#define CFG_CROP_Y              30U                          /* 略偏上，给人脸留位置 */

/* ==========================================================================
 * 4. 采集质量门限（太暗/太亮/对比度太低时提示重拍）
 *    灰度均值 0~255；对比度用 (P95 - P5) 近似
 * ========================================================================== */
#define CFG_BRIGHT_MIN          50U     /* 均值低于它 -> 太暗   */
#define CFG_BRIGHT_MAX          205U    /* 均值高于它 -> 太亮   */
#define CFG_CONTRAST_MIN        28U     /* 动态范围低于它 -> 太平/未对准 */

/* ==========================================================================
 * 5. 三种算法的判据阈值（默认起点值，必须用验证样本标定后填最终值）
 *    距离定义见 image_proc.h / algo_*.c 的注释：
 *      MSE   : 灰度差平方的平均值，0~65025，越小越像
 *      LBP   : 4x4 分区 LBP 直方图的卡方距离（归一化后），越小越像
 *      COLOR : 8x8x8 颜色直方图的卡方距离（对照特征）
 *      PCA   : k 维子空间里的欧氏距离
 *    开放集判定：最近邻距离 <= 阈值 才判"通过"，
 *                否则即使最近邻属于某人也要判"不通过"
 * ========================================================================== */
#define CFG_MSE_THRESHOLD       1200.0f
#define CFG_LBP_THRESHOLD       6.0f
#define CFG_COLOR_THRESHOLD     0.35f
#define CFG_PCA_THRESHOLD       2500.0f

/* 主成分个数 k：不能超过 (样本数 - 1)，也不能超过 PCA_MAX_K */
#define CFG_PCA_K               16U

/* ==========================================================================
 * 6. 任务周期（主循环按时间戳非阻塞调度）与超时
 * ========================================================================== */
#define CFG_KEY_PERIOD_MS       10U
#define CFG_UI_PERIOD_MS        200U
#define CFG_CAM_TIMEOUT_MS      400U
#define CFG_CAM_STALE_MS        5000U   /* 连续 5 秒无完整帧才停止重试 */
#define CFG_CAM_BYTE_SWAP       1       /* 与实验三 RGB565 高字节先输出配置配套 */
#define CFG_CAPTURE_TIMEOUT_MS  800U

/* ==========================================================================
 * 7. 统计：验证集 / 测试集分开计数
 *    实验要求"用验证图标定阈值、最终测试图只用一次"，
 *    所以固件把两套计数分开，LCD 上也能分别查看
 * ========================================================================== */
#define CFG_STAT_VALIDATION     0U      /* 真值来自验证集 */
#define CFG_STAT_TEST           1U      /* 真值来自最终测试集（只跑一次） */

#endif /* __CONFIG_H */
